// #1380: 한국어 공개 기사의 문장 말투를 다듬는 지침과 문체 예시입니다.
// 쓰기 단계(reporter/editor/completion/repair)에만 넣고 판정·fact-check 프롬프트에는 넣지 않습니다.
// 판정 기준이나 발행 관문은 바꾸지 않으며, 문장을 읽기 쉽게 만드는 방향만 안내합니다.
// 영어 번역에는 쓰지 않으므로 공유 지침(readable-prose-prompt)과 파일을 나눕니다.

function koreanProseStylePrompt() {
  return [
    '한국어 문장 말투: 보고서처럼 무겁게 쓰지 말고, 바쁜 엔지니어에게 설명하듯 자연스러운 한국어로 쓰세요.',
    '핵심 대상(주어)을 문장 앞에 두세요. lead를 "~을 막기 위해", "~하도록" 같은 목적절로 시작하지 말고, 무엇이 어떻게 바뀌었는지를 먼저 말한 뒤 이유를 덧붙이세요.',
    '한 문장에는 조건을 하나만 담으세요. 세부 조건은 다음 문장으로 넘기고, 한 문장이 길어지면 둘로 나누세요. 이때 조건을 삭제하지 말고 해당 주장 바로 옆 문장에 유지하세요.',
    '독자가 모를 수 있는 개념은 한 문장으로 먼저 풀어 준 뒤에 쓰세요. 풀이는 원문이 뒷받침하는 범위 안에서만 하세요.',
    '증상이나 질문에서 출발하는 소제목("왜 검은색이 회색으로 보였나요?")을 쓸 수 있습니다. 강제하지 않으며, 소제목 개수와 금지 라벨 규칙은 그대로 따르세요.',
    '번역투를 줄이세요. "~에 대해", "~를 통해", "~에 있어", "~되어진다", "~을 위해"를 남발하지 말고 "~을", "~로", "~할 때", "~됩니다"처럼 풀어 쓰세요. 연결어미 바로 뒤에 쉼표를 붙이지 마세요.',
    '명사를 겹쳐 동작을 숨기지 마세요. "재시도 요청 전송이 수행됩니다"는 주체가 원문에 있으면 "클라이언트가 요청을 다시 보냅니다"처럼 쓰세요. API·테스트 식별자는 원문대로 두고 주변 문장을 한국어 어순으로 다듬으세요.',
    '"~할 수 있다"나 "~로 보인다"처럼 원문이 확정하지 않은 표현을 확정형으로 바꾸지 마세요. 문장을 쉽게 만드는 일과 주장의 강도를 바꾸는 일은 별개입니다.'
  ].join('\n');
}

